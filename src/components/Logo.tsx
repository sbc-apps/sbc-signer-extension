import logoUrl from '@/assets/logo.svg';
import { cn } from '@/lib/utils';

interface LogoProps {
  /** Tailwind size classes for the rendered logo, e.g. `size-7`. */
  className?: string;
  /** Accessible label. Defaults to empty (decorative). */
  alt?: string;
}

/**
 * The SBC logo, rendered as an HTML element whose background color
 * is the live theme primary and whose CSS mask is the bundled logo SVG.
 *
 * This mirrors Ditto's DittoLogo trick (ditto/src/components/DittoLogo.tsx):
 * filling the SVG silhouette with `var(--primary)` instead of shipping
 * a recolored asset means the logo automatically picks up whatever
 * primary color the user's active profile theme defines (kind 16767).
 *
 * The SVG itself is bundled by Vite as a hashed asset URL, so it works
 * uniformly inside the popup, prompt, and options windows without
 * needing manifest web_accessible_resources entries.
 */
export function Logo({ className, alt = '' }: LogoProps) {
  // The logo asset URL comes from a `import` statement, so the value
  // is generated by Vite at build time and cannot be influenced by
  // event data — safe to interpolate directly into a CSS `url(...)`.
  const maskImage = `url(${logoUrl})`;

  return (
    <div
      role="img"
      aria-label={alt}
      // Tailwind's `bg-primary` resolves to `var(--primary)`, which the
      // active profile theme overrides at runtime. The mask properties
      // are set inline because the size and shape of each instance is
      // controlled by the className passed in by the caller; the mask
      // URL itself is constant for the lifetime of the page.
      style={{
        maskImage,
        WebkitMaskImage: maskImage,
        maskSize: 'contain',
        WebkitMaskSize: 'contain',
        maskRepeat: 'no-repeat',
        WebkitMaskRepeat: 'no-repeat',
        maskPosition: 'center',
        WebkitMaskPosition: 'center',
      }}
      className={cn('bg-primary', className)}
    />
  );
}
